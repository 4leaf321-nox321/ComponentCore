def name_of(nominal: float) -> str:
    """호칭 지름 → 표의 이름(6 → `M6`, 2.5 → `M2.5`)."""
    return f"M{nominal:g}"


def head(nominal: float, kind: str) -> tuple[float, float, float]:
    """볼트 머리 — (바깥 치수, 높이, 육각 구멍 맞변).

    소켓은 바깥 치수가 머리 지름, 육각은 **맞변**이다(그리는 쪽이 꼭짓점 반지름 s / √3 로
    바꾼다). 육각 머리에는 구멍이 없다(0). 표에 없는 호칭(M7 같은)은 예전 비례로 그린다 —
    머리 지름 1.5d, 육각 높이 0.65d, 소켓 높이 1.0d, 육각 구멍 0.8d."""
    name = name_of(nominal)
    if kind == "socket":
        if name in SOCKET_HEADS:
            return SOCKET_HEADS[name]
        return 1.5 * nominal, nominal, 0.8 * nominal
    if name in HEX_HEADS:
        across, height = HEX_HEADS[name]
        return across, height, 0.0
    return 1.5 * nominal * 3**0.5 / 2, 0.65 * nominal, 0.0


def washer(nominal: float) -> tuple[float, float]:
    """볼트 밑 와셔 — (바깥지름, 두께). 표에 없으면 예전 비례(지름 2d, 두께 0.2d)."""
    name = name_of(nominal)
    if name in WASHERS:
        _inner, outer, thickness = WASHERS[name]
        return outer, thickness
    return 2 * nominal, 0.2 * nominal


def thread_for(diameter: float) -> str | None:
    """구멍 지름에 맞는 나사 — 여유 구멍(±0.3) 또는 탭 드릴(±0.2) 중 **가장 가까운 것.**

    표가 M1.6 ~ M24 로 넓어지면서 한 지름이 둘에 걸린다 — 지름 1.6 은 M2 의 탭 드릴이자 M1.6 의
    여유 구멍(1.8)에서 0.2 다. 표 순서대로 첫 일치를 고르면 작은 쪽(M1.6)이 늘 이긴다. 같은
    거리면 여유 구멍을 먼저 본다(볼트가 지나가는 구멍이 흔하다). 맞는 것이 없으면 None."""
    best: tuple[float, int, str] | None = None
    for name, (tap, clearance, *_rest) in THREADS.items():
        for gap, rank, limit in (
            (abs(diameter - clearance), 0, 0.3),
            (abs(diameter - tap), 1, 0.2),
        ):
            if gap <= limit + 1e-9 and (best is None or (gap, rank) < best[:2]):
                best = (gap, rank, name)
    return best[2] if best else None
